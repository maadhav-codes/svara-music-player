package app.svara.youtube

import org.junit.Assert.*
import org.junit.Test

class StudioAudioPolicyTest {
    @Test fun rejectsCinematicAndPerformanceVersions() {
        for (title in listOf(
            "Song (Official Music Video)", "Song - Official Video", "Full Video Song",
            "Song (Lyric Video)", "Song - Movie Scene", "Song (Live)",
            "Song [Live at Wembley]", "Song - Live from London", "Unplugged session",
            "Artist concert", "Cinematic Version"
        )) assertFalse(title, StudioAudioPolicy.accepts(title))
    }

    @Test fun retainsSongNamesAndStudioVariants() {
        for (title in listOf(
            "Video Games", "Live and Let Die", "The Sound of Silence",
            "Song (Official Audio)", "Song (Studio Version)", "Song (Remastered)",
            "Song (Acoustic Version)", "Song (Extended Mix)"
        )) assertTrue(title, StudioAudioPolicy.accepts(title))
    }

    @Test fun artTrackMetadataNeedsBothMarkers() {
        assertTrue(StudioAudioPolicy.hasArtTrackMetadata(
            "Provided to YouTube by Distributor<br>Track<br>Auto-generated by YouTube."
        ))
        for (description in listOf(
            "Artist - Topic", "Official Audio", "VEVO",
            "Provided to YouTube by Distributor", "Auto-generated by YouTube", ""
        )) assertFalse(description, StudioAudioPolicy.hasArtTrackMetadata(description))
    }
}
