package app.svara.youtube

/** Recording selection is separate from choosing an audio-only transport. */
internal object StudioAudioPolicy {
    private val videoVersion = Regex(
        """\b(official\s+(music\s+)?video|music\s+video|full\s+video|video\s+song|lyric\s+video|cinematic\s+version|movie\s+scene|short\s+film)\b""",
        RegexOption.IGNORE_CASE
    )
    private val liveVersion = Regex(
        """\b(live\s+(at|from|in|performance|version|session)|concert|unplugged)\b|[\[(]\s*live\b""",
        RegexOption.IGNORE_CASE
    )

    fun accepts(title: String): Boolean =
        !videoVersion.containsMatchIn(title) && !liveVersion.containsMatchIn(title)

    // This is supporting metadata evidence, not an audio-content classifier.
    // Topic/VEVO channel names and "official audio" titles alone prove nothing.
    fun hasArtTrackMetadata(description: String): Boolean =
        description.contains("Provided to YouTube by", ignoreCase = true) &&
            description.contains("Auto-generated by YouTube", ignoreCase = true)
}
